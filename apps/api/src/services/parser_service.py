"""Tree-sitter AST Parser Service for CodePilot Module 3.2.

Provides static parsing of repository source code into:
- RepoFile metadata
- Symbols (Functions, Classes, Methods, Interfaces)
- FileImports (Module imports, symbols, aliases)
- CodeChunks (Semantic code chunks with token counts and content hashes)
- File-level summaries

CRITICAL SECURITY REQUIREMENT:
Repository source code is NEVER executed or evaluated dynamically.
All code analysis is performed purely via static AST inspection.
"""

import hashlib
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Any

import tree_sitter
from tree_sitter import Language, Parser
import tree_sitter_python
import tree_sitter_javascript
import tree_sitter_typescript

# Initialize Tree-sitter parsers
PY_LANGUAGE = Language(tree_sitter_python.language())
JS_LANGUAGE = Language(tree_sitter_javascript.language())
TS_LANGUAGE = Language(tree_sitter_typescript.language_typescript())
TSX_LANGUAGE = Language(tree_sitter_typescript.language_tsx())

# Binary file extensions that should not be text-parsed
BINARY_EXTENSIONS = {
    ".png", ".jpg", ".jpeg", ".gif", ".ico", ".svg", ".webp", ".bmp",
    ".pdf", ".zip", ".tar", ".gz", ".7z", ".rar", ".exe", ".dll", ".so",
    ".dylib", ".class", ".pyc", ".pyo", ".bin", ".dat", ".db", ".sqlite",
    ".woff", ".woff2", ".ttf", ".eot", ".mp4", ".mp3", ".wav"
}

# Ignore directories for scanning
IGNORE_DIRS = {
    ".git", ".svn", ".hg", "node_modules", "dist", "build",
    "__pycache__", ".venv", "venv", ".idea", ".vscode", "coverage", ".pytest_cache"
}


@dataclass
class ParsedSymbol:
    name: str
    qualified_name: str
    kind: str  # FUNCTION, CLASS, METHOD, INTERFACE, VARIABLE
    scope: Optional[str] = None
    start_line: int = 1
    end_line: int = 1
    start_column: int = 0
    end_column: int = 0
    signature: Optional[str] = None
    docstring: Optional[str] = None


@dataclass
class ParsedImport:
    source_module: str
    imported_symbol: Optional[str] = None
    alias: Optional[str] = None
    line_number: int = 1


@dataclass
class ParsedChunk:
    content: str
    chunk_type: str  # FUNCTION, CLASS, METHOD, MODULE, BLOCK
    start_line: int
    end_line: int
    token_count: int
    content_hash: str
    symbol_name: Optional[str] = None


@dataclass
class ParsedFile:
    path: str
    filename: str
    extension: Optional[str]
    language: Optional[str]
    content_hash: str
    size_bytes: int
    line_count: int
    summary: Optional[str] = None
    symbols: List[ParsedSymbol] = field(default_factory=list)
    imports: List[ParsedImport] = field(default_factory=list)
    chunks: List[ParsedChunk] = field(default_factory=list)
    is_binary: bool = False


class ASTParserService:
    """Static AST parser using Tree-sitter for multi-language codebase analysis."""

    def __init__(self):
        self._parsers: Dict[str, Parser] = {
            "python": Parser(PY_LANGUAGE),
            "javascript": Parser(JS_LANGUAGE),
            "typescript": Parser(TS_LANGUAGE),
            "tsx": Parser(TSX_LANGUAGE),
        }

    def detect_language(self, file_path: str) -> Optional[str]:
        """Detect language from file path or extension."""
        ext = os.path.splitext(file_path)[1].lower()
        if ext == ".py":
            return "python"
        elif ext in {".js", ".jsx", ".mjs", ".cjs"}:
            return "javascript"
        elif ext in {".ts", ".mts", ".cts"}:
            return "typescript"
        elif ext == ".tsx":
            return "tsx"
        elif ext in {".json", ".jsonc"}:
            return "json"
        elif ext in {".md", ".markdown"}:
            return "markdown"
        elif ext in {".html", ".htm"}:
            return "html"
        elif ext in {".css", ".scss", ".sass", ".less"}:
            return "css"
        elif ext in {".yaml", ".yml"}:
            return "yaml"
        elif ext in {".sh", ".bash", ".zsh"}:
            return "shell"
        elif ext in {".sql"}:
            return "sql"
        return None

    def is_binary_file(self, file_path: Path, sample_bytes: bytes) -> bool:
        """Check if file is binary by extension or null byte presence."""
        if file_path.suffix.lower() in BINARY_EXTENSIONS:
            return True
        if b"\x00" in sample_bytes[:1024]:
            return True
        return False

    def parse_file(
        self,
        rel_path: str,
        full_path: Path,
        generate_summary: bool = False
    ) -> Optional[ParsedFile]:
        """Parse a single file from disk into AST structures.

        Never executes code. Handles syntax errors and unsupported files gracefully.
        File-level summaries are not generated by default to keep ingestion fast and decoupled.
        """
        try:
            if not full_path.is_file():
                return None

            size_bytes = full_path.stat().st_size
            sample_bytes = full_path.read_bytes()

            filename = full_path.name
            extension = full_path.suffix.lower() if full_path.suffix else None
            content_hash = hashlib.sha256(sample_bytes).hexdigest()

            # Check binary
            if self.is_binary_file(full_path, sample_bytes):
                return ParsedFile(
                    path=rel_path.replace("\\", "/"),
                    filename=filename,
                    extension=extension,
                    language=None,
                    content_hash=content_hash,
                    size_bytes=size_bytes,
                    line_count=0,
                    summary=f"Binary file ({size_bytes} bytes)" if generate_summary else None,
                    is_binary=True
                )

            # Decode text safely
            try:
                content = sample_bytes.decode("utf-8")
            except UnicodeDecodeError:
                content = sample_bytes.decode("latin-1", errors="replace")

            lines = content.splitlines()
            line_count = len(lines)
            language = self.detect_language(rel_path)

            symbols: List[ParsedSymbol] = []
            imports: List[ParsedImport] = []
            chunks: List[ParsedChunk] = []

            # Perform AST parsing if supported language
            if language in {"python", "javascript", "typescript", "tsx"}:
                parser = self._parsers[language]
                tree = parser.parse(sample_bytes)

                if language == "python":
                    symbols, imports = self._extract_python(tree.root_node, lines, sample_bytes)
                elif language in {"javascript", "typescript", "tsx"}:
                    symbols, imports = self._extract_js_ts(tree.root_node, lines, sample_bytes, language)

            # Generate semantic chunks
            chunks = self._generate_chunks(content, lines, symbols)

            # Only generate file summary if explicitly requested
            summary = self._generate_file_summary(filename, language, line_count, symbols, imports) if generate_summary else None

            return ParsedFile(
                path=rel_path.replace("\\", "/"),
                filename=filename,
                extension=extension,
                language=language,
                content_hash=content_hash,
                size_bytes=size_bytes,
                line_count=line_count,
                summary=summary,
                symbols=symbols,
                imports=imports,
                chunks=chunks,
                is_binary=False
            )
        except Exception as e:
            # Resilient fallback: return basic file metadata without failing the whole repo
            try:
                size_bytes = full_path.stat().st_size
            except Exception:
                size_bytes = 0
            return ParsedFile(
                path=rel_path.replace("\\", "/"),
                filename=full_path.name,
                extension=full_path.suffix.lower() if full_path.suffix else None,
                language=self.detect_language(rel_path),
                content_hash=hashlib.sha256(str(rel_path).encode()).hexdigest(),
                size_bytes=size_bytes,
                line_count=0,
                summary=None,
                is_binary=False
            )

    def _extract_python(
        self,
        root_node: tree_sitter.Node,
        lines: List[str],
        source_bytes: bytes
    ) -> Tuple[List[ParsedSymbol], List[ParsedImport]]:
        """Extract Python symbols and imports from AST."""
        symbols: List[ParsedSymbol] = []
        imports: List[ParsedImport] = []

        def get_node_text(node: tree_sitter.Node) -> str:
            return source_bytes[node.start_byte:node.end_byte].decode("utf-8", errors="replace")

        def extract_docstring(body_node: Optional[tree_sitter.Node]) -> Optional[str]:
            if not body_node:
                return None
            for child in body_node.children:
                if child.type == "expression_statement":
                    for sub in child.children:
                        if sub.type == "string":
                            raw = get_node_text(sub).strip("\"'")
                            return raw.strip()
            return None

        def extract_signature(node: tree_sitter.Node) -> str:
            start_l = node.start_point.row
            line_txt = lines[start_l].strip() if start_l < len(lines) else ""
            if ":" in line_txt:
                line_txt = line_txt.split(":")[0] + ":"
            return line_txt

        def traverse(node: tree_sitter.Node, current_class: Optional[str] = None):
            # 1. Imports
            if node.type == "import_statement":
                line_num = node.start_point.row + 1
                for child in node.children:
                    if child.type == "dotted_name":
                        imports.append(ParsedImport(source_module=get_node_text(child), line_number=line_num))
                    elif child.type == "aliased_import":
                        dotted = child.child_by_field_name("name")
                        alias = child.child_by_field_name("alias")
                        if dotted:
                            imports.append(ParsedImport(
                                source_module=get_node_text(dotted),
                                alias=get_node_text(alias) if alias else None,
                                line_number=line_num
                            ))
                return

            elif node.type == "import_from_statement":
                line_num = node.start_point.row + 1
                module_node = node.child_by_field_name("module_name")
                module_name = get_node_text(module_node) if module_node else ""
                for child in node.children:
                    if child.type == "dotted_name" and child != module_node:
                        imports.append(ParsedImport(
                            source_module=module_name,
                            imported_symbol=get_node_text(child),
                            line_number=line_num
                        ))
                    elif child.type == "aliased_import":
                        name_node = child.child_by_field_name("name")
                        alias_node = child.child_by_field_name("alias")
                        if name_node:
                            imports.append(ParsedImport(
                                source_module=module_name,
                                imported_symbol=get_node_text(name_node),
                                alias=get_node_text(alias_node) if alias_node else None,
                                line_number=line_num
                            ))
                return

            # 2. Classes
            elif node.type == "class_definition":
                name_node = node.child_by_field_name("name")
                if name_node:
                    class_name = get_node_text(name_node)
                    body_node = node.child_by_field_name("body")
                    doc = extract_docstring(body_node)
                    sig = extract_signature(node)
                    symbols.append(ParsedSymbol(
                        name=class_name,
                        qualified_name=f"{current_class}.{class_name}" if current_class else class_name,
                        kind="CLASS",
                        scope=current_class,
                        start_line=node.start_point.row + 1,
                        end_line=node.end_point.row + 1,
                        start_column=node.start_point.column,
                        end_column=node.end_point.column,
                        signature=sig,
                        docstring=doc
                    ))

                    if body_node:
                        for b_child in body_node.children:
                            traverse(b_child, current_class=class_name)
                    return

            # 3. Functions / Methods
            elif node.type == "function_definition":
                fn_name_node = node.child_by_field_name("name")
                if fn_name_node:
                    fn_name = get_node_text(fn_name_node)
                    body_node = node.child_by_field_name("body")
                    doc = extract_docstring(body_node)
                    sig = extract_signature(node)
                    kind = "METHOD" if current_class else "FUNCTION"
                    qual = f"{current_class}.{fn_name}" if current_class else fn_name
                    symbols.append(ParsedSymbol(
                        name=fn_name,
                        qualified_name=qual,
                        kind=kind,
                        scope=current_class,
                        start_line=node.start_point.row + 1,
                        end_line=node.end_point.row + 1,
                        start_column=node.start_point.column,
                        end_column=node.end_point.column,
                        signature=sig,
                        docstring=doc
                    ))
                    return

            # Recurse for decorators, wrappers, ERROR nodes, etc.
            for child in node.children:
                traverse(child, current_class=current_class)

        traverse(root_node)
        return symbols, imports

    def _extract_js_ts(
        self,
        root_node: tree_sitter.Node,
        lines: List[str],
        source_bytes: bytes,
        language: str
    ) -> Tuple[List[ParsedSymbol], List[ParsedImport]]:
        """Extract JavaScript / TypeScript symbols and imports from AST."""
        symbols: List[ParsedSymbol] = []
        imports: List[ParsedImport] = []

        def get_node_text(node: tree_sitter.Node) -> str:
            return source_bytes[node.start_byte:node.end_byte].decode("utf-8", errors="replace")

        def extract_signature(node: tree_sitter.Node) -> str:
            start_l = node.start_point.row
            line_txt = lines[start_l].strip() if start_l < len(lines) else ""
            if "{" in line_txt:
                line_txt = line_txt.split("{")[0].strip()
            return line_txt

        def process_node(node: tree_sitter.Node, scope: Optional[str] = None):
            # Unwrap export statements
            if node.type == "export_statement":
                for child in node.children:
                    if child.type in {
                        "class_declaration", "function_declaration", "generator_function_declaration",
                        "lexical_declaration", "variable_declaration", "interface_declaration"
                    }:
                        process_node(child, scope)
                return

            # 1. Imports
            if node.type == "import_statement":
                line_num = node.start_point.row + 1
                source_node = node.child_by_field_name("source")
                source_val = get_node_text(source_node).strip("\"'") if source_node else ""
                for child in node.children:
                    if child.type == "import_clause":
                        for clause_child in child.children:
                            if clause_child.type == "identifier":
                                imports.append(ParsedImport(
                                    source_module=source_val,
                                    imported_symbol="default",
                                    alias=get_node_text(clause_child),
                                    line_number=line_num
                                ))
                            elif clause_child.type == "named_imports":
                                for spec in clause_child.children:
                                    if spec.type == "import_specifier":
                                        name_n = spec.child_by_field_name("name")
                                        alias_n = spec.child_by_field_name("alias")
                                        if name_n:
                                            imports.append(ParsedImport(
                                                source_module=source_val,
                                                imported_symbol=get_node_text(name_n),
                                                alias=get_node_text(alias_n) if alias_n else None,
                                                line_number=line_num
                                            ))
                            elif clause_child.type == "namespace_import":
                                for ns_child in clause_child.children:
                                    if ns_child.type == "identifier":
                                        imports.append(ParsedImport(
                                            source_module=source_val,
                                            alias=get_node_text(ns_child),
                                            line_number=line_num
                                        ))

            # 2. CommonJS require imports & Arrow functions
            elif node.type in {"lexical_declaration", "variable_declaration"}:
                line_num = node.start_point.row + 1
                for decl in node.children:
                    if decl.type == "variable_declarator":
                        name_node = decl.child_by_field_name("name")
                        val_node = decl.child_by_field_name("value")
                        if not name_node or not val_node:
                            continue
                        name_str = get_node_text(name_node)

                        # Check require(...)
                        if val_node.type == "call_expression":
                            fn_n = val_node.child_by_field_name("function")
                            args_n = val_node.child_by_field_name("arguments")
                            if fn_n and get_node_text(fn_n) == "require" and args_n:
                                req_src = get_node_text(args_n).strip("()\"' ")
                                imports.append(ParsedImport(
                                    source_module=req_src,
                                    imported_symbol=name_str,
                                    line_number=line_num
                                ))

                        # Check arrow function: const foo = () => ...
                        elif val_node.type in {"arrow_function", "function"}:
                            sig = extract_signature(decl)
                            symbols.append(ParsedSymbol(
                                name=name_str,
                                qualified_name=f"{scope}.{name_str}" if scope else name_str,
                                kind="FUNCTION",
                                scope=scope,
                                start_line=decl.start_point.row + 1,
                                end_line=decl.end_point.row + 1,
                                start_column=decl.start_point.column,
                                end_column=decl.end_point.column,
                                signature=sig
                            ))

            # 3. Classes
            elif node.type == "class_declaration":
                name_node = node.child_by_field_name("name")
                if name_node:
                    class_name = get_node_text(name_node)
                    sig = extract_signature(node)
                    symbols.append(ParsedSymbol(
                        name=class_name,
                        qualified_name=f"{scope}.{class_name}" if scope else class_name,
                        kind="CLASS",
                        scope=scope,
                        start_line=node.start_point.row + 1,
                        end_line=node.end_point.row + 1,
                        start_column=node.start_point.column,
                        end_column=node.end_point.column,
                        signature=sig
                    ))

                    body_node = node.child_by_field_name("body")
                    if body_node:
                        for m_child in body_node.children:
                            if m_child.type == "method_definition":
                                m_name_node = m_child.child_by_field_name("name")
                                if m_name_node:
                                    m_name = get_node_text(m_name_node)
                                    m_sig = extract_signature(m_child)
                                    symbols.append(ParsedSymbol(
                                        name=m_name,
                                        qualified_name=f"{class_name}.{m_name}",
                                        kind="METHOD",
                                        scope=class_name,
                                        start_line=m_child.start_point.row + 1,
                                        end_line=m_child.end_point.row + 1,
                                        start_column=m_child.start_point.column,
                                        end_column=m_child.end_point.column,
                                        signature=m_sig
                                    ))

            # 4. Functions
            elif node.type in {"function_declaration", "generator_function_declaration"}:
                name_node = node.child_by_field_name("name")
                if name_node:
                    fn_name = get_node_text(name_node)
                    sig = extract_signature(node)
                    symbols.append(ParsedSymbol(
                        name=fn_name,
                        qualified_name=f"{scope}.{fn_name}" if scope else fn_name,
                        kind="FUNCTION",
                        scope=scope,
                        start_line=node.start_point.row + 1,
                        end_line=node.end_point.row + 1,
                        start_column=node.start_point.column,
                        end_column=node.end_point.column,
                        signature=sig
                    ))

            # 5. Interfaces (TypeScript)
            elif node.type == "interface_declaration":
                name_node = node.child_by_field_name("name")
                if name_node:
                    iface_name = get_node_text(name_node)
                    sig = extract_signature(node)
                    symbols.append(ParsedSymbol(
                        name=iface_name,
                        qualified_name=iface_name,
                        kind="INTERFACE",
                        scope=None,
                        start_line=node.start_point.row + 1,
                        end_line=node.end_point.row + 1,
                        start_column=node.start_point.column,
                        end_column=node.end_point.column,
                        signature=sig
                    ))

        for child in root_node.children:
            process_node(child)

        return symbols, imports

    def _generate_chunks(
        self,
        full_content: str,
        lines: List[str],
        symbols: List[ParsedSymbol]
    ) -> List[ParsedChunk]:
        """Generate semantic code chunks bound to extracted symbols or logical code windows."""
        chunks: List[ParsedChunk] = []

        def token_count(text: str) -> int:
            return max(1, len(text.split()))

        def hash_content(text: str) -> str:
            return hashlib.sha256(text.encode("utf-8")).hexdigest()

        # 1. Chunks for top-level symbols (Classes, Functions)
        covered_lines = set()
        for sym in symbols:
            # We chunk top-level classes and functions (methods can be included or chunked separately)
            if sym.kind in {"CLASS", "FUNCTION", "INTERFACE"}:
                s_idx = max(0, sym.start_line - 1)
                e_idx = min(len(lines), sym.end_line)
                chunk_lines = lines[s_idx:e_idx]
                chunk_text = "\n".join(chunk_lines).strip()
                if chunk_text:
                    chunks.append(ParsedChunk(
                        content=chunk_text,
                        chunk_type=sym.kind,
                        start_line=sym.start_line,
                        end_line=sym.end_line,
                        token_count=token_count(chunk_text),
                        content_hash=hash_content(chunk_text),
                        symbol_name=sym.name
                    ))
                    for line_idx in range(sym.start_line, sym.end_line + 1):
                        covered_lines.add(line_idx)

        # 2. Chunk remaining uncovered code (e.g. module header, imports, top-level constants)
        # Group contiguous uncovered lines into blocks of up to 60 lines
        uncovered_blocks: List[Tuple[int, int]] = []
        curr_start = None
        for i in range(1, len(lines) + 1):
            if i not in covered_lines and lines[i - 1].strip():
                if curr_start is None:
                    curr_start = i
                elif (i - curr_start) >= 60:
                    uncovered_blocks.append((curr_start, i))
                    curr_start = i + 1
            else:
                if curr_start is not None:
                    uncovered_blocks.append((curr_start, i - 1))
                    curr_start = None
        if curr_start is not None:
            uncovered_blocks.append((curr_start, len(lines)))

        for b_start, b_end in uncovered_blocks:
            s_idx = max(0, b_start - 1)
            e_idx = min(len(lines), b_end)
            block_lines = lines[s_idx:e_idx]
            block_text = "\n".join(block_lines).strip()
            if block_text:
                chunks.append(ParsedChunk(
                    content=block_text,
                    chunk_type="MODULE" if b_start <= 30 else "BLOCK",
                    start_line=b_start,
                    end_line=b_end,
                    token_count=token_count(block_text),
                    content_hash=hash_content(block_text),
                    symbol_name=None
                ))

        # Fallback if no chunks generated and file not empty
        if not chunks and full_content.strip():
            chunks.append(ParsedChunk(
                content=full_content[:5000].strip(),
                chunk_type="BLOCK",
                start_line=1,
                end_line=len(lines),
                token_count=token_count(full_content),
                content_hash=hash_content(full_content),
                symbol_name=None
            ))

        return chunks

    def _generate_file_summary(
        self,
        filename: str,
        language: Optional[str],
        line_count: int,
        symbols: List[ParsedSymbol],
        imports: List[ParsedImport]
    ) -> str:
        """Synthesize structured, deterministic file-level summary."""
        classes = [s.name for s in symbols if s.kind == "CLASS"]
        functions = [s.name for s in symbols if s.kind == "FUNCTION"]
        interfaces = [s.name for s in symbols if s.kind == "INTERFACE"]
        unique_modules = list(dict.fromkeys([imp.source_module for imp in imports if imp.source_module]))

        lang_label = language.capitalize() if language else "Source"
        summary_parts = [f"{lang_label} file with {line_count} lines."]

        if classes:
            summary_parts.append(f"Classes ({len(classes)}): {', '.join(classes[:5])}{'...' if len(classes) > 5 else ''}.")
        if functions:
            summary_parts.append(f"Functions ({len(functions)}): {', '.join(functions[:8])}{'...' if len(functions) > 8 else ''}.")
        if interfaces:
            summary_parts.append(f"Interfaces ({len(interfaces)}): {', '.join(interfaces[:5])}.")
        if unique_modules:
            summary_parts.append(f"Imports ({len(unique_modules)}): {', '.join(unique_modules[:8])}{'...' if len(unique_modules) > 8 else ''}.")

        if not symbols and not imports:
            if line_count == 0:
                summary_parts.append("Empty file.")
            else:
                summary_parts.append("Contains configuration, documentation, or declaration statements.")

        return " ".join(summary_parts)


