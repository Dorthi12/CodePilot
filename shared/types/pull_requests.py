"""Shared types, enums, and data models for Mastermind Feature 7 (Pull Request Reviews).

Specifications:
- Master Architecture Specification v2.1 §10 (M7), §6.5, §6.6, §11.3 (Endpoints 091–096)
- API and Data Specification v1.0 §3.3 (091–096), §3.4.15, §3.10, §4.5, §4.6
- Security & Testing Specification v1.0 §7.3.10 (SEC-API-28..31), §7.9, §8.9 (AI-16)
- System Design Specification v1.0 §9.7, §12.3
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import uuid4
from pydantic import BaseModel, Field

from shared.types.agent import FindingSeverity, RunStatus
from shared.types.findings import FindingEvidence


class PRState(str, Enum):
    """Lifecycle state of a Pull Request."""
    OPEN = "OPEN"
    CLOSED = "CLOSED"
    MERGED = "MERGED"


class FileChangeStatus(str, Enum):
    """File status in a PR diff."""
    ADDED = "added"
    MODIFIED = "modified"
    REMOVED = "removed"
    RENAMED = "renamed"


class ReviewCommentStatus(str, Enum):
    """Status of a PR review comment (API Spec §4.6)."""
    DRAFT = "DRAFT"
    EDITED = "EDITED"
    DISCARDED = "DISCARDED"
    PUBLISHED = "PUBLISHED"


class WebhookDeliveryStatus(str, Enum):
    """Status of webhook delivery processing."""
    RECEIVED = "RECEIVED"
    PROCESSED = "PROCESSED"
    IGNORED = "IGNORED"
    FAILED = "FAILED"


class DiffHunk(BaseModel):
    """Parsed hunk information from unified diff."""
    file_path: str
    orig_start: int
    orig_len: int
    mod_start: int
    mod_len: int
    header: str
    added_lines: List[int] = Field(default_factory=list)  # 1-based line numbers in head file
    deleted_lines: List[int] = Field(default_factory=list)
    context_lines: List[int] = Field(default_factory=list)


class PRFile(BaseModel):
    """Changed file in a PR."""
    id: str = Field(default_factory=lambda: str(uuid4()))
    pull_request_id: str
    path: str
    status: FileChangeStatus = FileChangeStatus.MODIFIED
    additions: int = 0
    deletions: int = 0
    hunks: List[DiffHunk] = Field(default_factory=list)
    mapped_symbols: List[str] = Field(default_factory=list)


class ReviewComment(BaseModel):
    """Inline review comment generated by Mastermind 7."""
    id: str = Field(default_factory=lambda: str(uuid4()))
    run_id: str
    pull_request_id: str
    file_path: str
    side: str = "RIGHT"  # LEFT (base) or RIGHT (head)
    line: int
    finding_id: Optional[str] = None
    body: str
    severity: FindingSeverity = FindingSeverity.MEDIUM
    status: ReviewCommentStatus = ReviewCommentStatus.DRAFT
    github_comment_id: Optional[int] = None
    evidence: List[FindingEvidence] = Field(default_factory=list)
    version: int = 1
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class PullRequest(BaseModel):
    """Pull request entity matching PostgreSQL schema and API Spec §4.5."""
    id: str = Field(default_factory=lambda: str(uuid4()))
    tenant_id: Optional[str] = "default-tenant"
    repository_id: str
    number: int
    title: str
    author_login: str
    base_ref: str
    head_ref: str
    head_repo_full_name: Optional[str] = None
    base_sha: str
    head_sha: str
    base_snapshot_id: Optional[str] = None
    head_snapshot_id: Optional[str] = None
    state: PRState = PRState.OPEN
    is_fork: bool = False
    draft: bool = False
    last_synced_at: Optional[datetime] = None
    latest_review_run_id: Optional[str] = None
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class ReviewRunRecord(BaseModel):
    """PR Review run entity pinned to base_sha and head_sha."""
    id: str = Field(default_factory=lambda: str(uuid4()))
    pull_request_id: str
    repository_id: str
    base_sha: str
    head_sha: str
    review_profile: str = "standard"
    status: RunStatus = RunStatus.COMPLETED
    summary: str = ""
    impacted_modules: List[str] = Field(default_factory=list)
    tests_to_run: List[str] = Field(default_factory=list)
    comments: List[ReviewComment] = Field(default_factory=list)
    approval_state: str = "DRAFT"  # DRAFT, APPROVED, PUBLISHED, STALE
    stale: bool = False
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    completed_at: Optional[datetime] = None


class WebhookDelivery(BaseModel):
    """Webhook delivery audit record for deduplication and tracing (API Spec §3.10)."""
    delivery_id: str
    tenant_id: Optional[str] = None
    event: str
    repository_id: Optional[str] = None
    received_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    status: WebhookDeliveryStatus = WebhookDeliveryStatus.RECEIVED


class AuditEventRecord(BaseModel):
    """Immutable audit log event (API Spec §4.5, SEC-AUD-02)."""
    id: str = Field(default_factory=lambda: str(uuid4()))
    tenant_id: Optional[str] = "default-tenant"
    actor_id: str = "system"
    actor_type: str = "USER"  # USER, AGENT, SERVICE, WEBHOOK, OPERATOR, SYSTEM
    action: str
    resource_type: str
    resource_id: str
    outcome: str = "SUCCESS"  # SUCCESS, DENIED, FAILURE
    reason_code: Optional[str] = None
    request_id: Optional[str] = None
    trace_id: Optional[str] = None
    approval_id: Optional[str] = None
    metadata: Dict[str, Any] = Field(default_factory=dict)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
